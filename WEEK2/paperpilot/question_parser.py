"""
question_parser.py - Robust question segmentation from raw exam paper text.

Detects common numbering formats (e.g. '1.', 'Q2', '1(a)', '(i)'), avoids
false positives from exam instructions/metadata, and preserves source page
references and unparsed segments for human verification.
"""

from dataclasses import dataclass
import re
import uuid
from typing import List, Optional, Tuple, Union
from paperpilot.pdf_extractor import ExtractedDocument, ExtractedPage


@dataclass
class QuestionItem:
    """Represents an extracted question with source tracking."""
    id: str
    question_number: str
    text: str
    raw_text: str
    source_file: str
    source_page: int
    subject: str
    year: Optional[int] = None
    marks: Optional[str] = None

    def to_dict(self) -> dict:
        """Serializes question item into a dictionary for DataFrames and JSON."""
        return {
            "id": self.id,
            "question_number": self.question_number,
            "text": self.text,
            "source_file": self.source_file,
            "source_page": self.source_page,
            "subject": self.subject,
            "year": self.year if self.year is not None else "Unknown",
            "marks": self.marks or "",
        }


@dataclass
class ParseResult:
    """Holds parsed questions alongside any unparsed headers/instructions."""
    questions: List[QuestionItem]
    unparsed_segments: List[str]
    total_parsed: int


# Common non-question prefixes to discard from question matching
FALSE_POSITIVE_PATTERNS = [
    r"^(time\s*(allowed|allotted)?\s*[:\-])",
    r"^(max(imum)?\s*marks\s*[:\-])",
    r"^(total\s*marks\s*[:\-])",
    r"^(roll\s*no\b)",
    r"^(page\s+\d+(\s+of\s+\d+)?)",
    r"^(\[\s*p\.?\s*t\.?\s*o\.?\s*\])",
    r"^(note\s*[:\-])",
    r"^(instructions?\s*[:\-])",
    r"^(attempt\s+(any|all)\s+\w+)",
    r"^(answer\s+(any|all)\s+\w+)",
    r"^(section\s*[-–—:]?\s*[a-z0-9]+)",
    r"^(part\s*[-–—:]?\s*[a-z0-9]+)",
    r"^(unit\s*[-–—:]?\s*[ivxlcdm0-9]+)",
    r"^(semester|b\.?\s*tech|examination|academic\s*year)",
]
FALSE_POSITIVE_REGEX = re.compile("|".join(FALSE_POSITIVE_PATTERNS), re.IGNORECASE)

# Question start marker regex:
# Matches patterns like:
# 1. or 1) or 1:
# Q1. or Q.1 or Question 1: or Q-1
# 1(a) or 1.(a) or 1.a)
# (a) or (b) or (i) or (ii)
QUESTION_START_REGEX = re.compile(
    r"^\s*("
    r"(?:Q(?:uestion)?[\s\.\-_]*\d+[\.\)\:\s]*(?:\([a-zA-Z0-9]+\)|[a-zA-Z]\b)?)"  # Q1, Question 2(a)
    r"|"
    r"(?:\d+[\.\)\:](?:\s*\([a-zA-Z0-9]+\)|\s*[a-zA-Z][\.\)])?)"  # 1., 1), 1(a), 1.a)
    r"|"
    r"(?:\d+\([a-zA-Z0-9]+\))"  # 1(a)
    r"|"
    r"(?:\([a-zA-Z0-9]+\)[\.\)]?)"  # (a), (i), (1)
    r")\s*(.*)",
    re.IGNORECASE,
)

# Marks pattern at the end of questions e.g. [10], (5 Marks), [4+6=10]
MARKS_REGEX = re.compile(
    r"(\[\s*\d+(?:\s*[\+\*\/]\s*\d+)*\s*(?:marks?|m)?\s*\]|\(\s*\d+\s*(?:marks?|m)\s*\))\s*$",
    re.IGNORECASE,
)


def is_false_positive_header(line: str) -> bool:
    """Checks whether a line is exam metadata rather than a question."""
    stripped = line.strip()
    if not stripped:
        return True
    return bool(FALSE_POSITIVE_REGEX.search(stripped))


def clean_question_body(text: str) -> str:
    """Normalizes excessive whitespace and newlines inside question text."""
    # Replace multiple internal newlines and spaces with single space
    cleaned = re.sub(r"\s+", " ", text).strip()
    return cleaned


def parse_questions_from_document(doc: ExtractedDocument) -> ParseResult:
    """
    Parses questions from an extracted PDF document.

    Iterates through each page, identifies question boundaries, accumulates
    multi-line question bodies, extracts marks if present, and captures
    unparsed headers or instructions.

    Parameters:
    -----------
    doc : ExtractedDocument
        The document generated by pdf_extractor.py.

    Returns:
    --------
    ParseResult
        Contains the list of parsed QuestionItems and unparsed segments.
    """
    questions: List[QuestionItem] = []
    unparsed_segments: List[str] = []

    current_number: Optional[str] = None
    current_lines: List[str] = []
    current_page: int = 1

    def flush_current_question():
        nonlocal current_number, current_lines, current_page
        if current_number and current_lines:
            raw_content = " ".join(current_lines).strip()
            marks_match = MARKS_REGEX.search(raw_content)
            marks_val = marks_match.group(1) if marks_match else None

            # Remove marks token from body if present
            cleaned_text = MARKS_REGEX.sub("", raw_content).strip()
            cleaned_text = clean_question_body(cleaned_text)

            # Avoid storing trivially empty questions (e.g. just a number with 1 character)
            if len(cleaned_text) >= 5:
                q_id = f"{doc.filename}_p{current_page}_{len(questions) + 1}_{uuid.uuid4().hex[:6]}"
                questions.append(
                    QuestionItem(
                        id=q_id,
                        question_number=current_number,
                        text=cleaned_text,
                        raw_text=raw_content,
                        source_file=doc.filename,
                        source_page=current_page,
                        subject=doc.subject,
                        year=doc.year,
                        marks=marks_val,
                    )
                )
            else:
                unparsed_segments.append(f"Skipped too-short question '{current_number}': {raw_content}")

        current_number = None
        current_lines = []

    for page in doc.pages:
        lines = page.text.splitlines()

        for line in lines:
            trimmed = line.strip()
            if not trimmed:
                continue

            # Check if this line is exam metadata (e.g. 'Time: 3 hrs', 'Section A')
            if is_false_positive_header(trimmed):
                if not current_number:
                    unparsed_segments.append(f"[Page {page.page_number}] {trimmed}")
                continue

            match = QUESTION_START_REGEX.match(trimmed)

            if match:
                # We found a new question start boundary!
                # Save previous question if one was being accumulated
                flush_current_question()

                marker = match.group(1).strip()
                remainder = match.group(2).strip()

                current_number = marker
                current_page = page.page_number
                if remainder:
                    current_lines.append(remainder)
            else:
                # Line belongs to the ongoing question, or is pre-question document text
                if current_number is not None:
                    current_lines.append(trimmed)
                else:
                    unparsed_segments.append(f"[Page {page.page_number}] {trimmed}")

    # Flush any remaining question at the end of the document
    flush_current_question()

    return ParseResult(
        questions=questions,
        unparsed_segments=unparsed_segments,
        total_parsed=len(questions),
    )


def parse_questions(
    doc_or_text: Union[ExtractedDocument, str],
    source_file: str = "unknown.pdf",
    subject: str = "General",
    year: Optional[int] = None,
) -> ParseResult:
    """
    Convenience wrapper that accepts either an ExtractedDocument or a raw text string,
    delegating to parse_questions_from_document.
    """
    if isinstance(doc_or_text, ExtractedDocument):
        return parse_questions_from_document(doc_or_text)

    page = ExtractedPage(page_number=1, text=doc_or_text, char_count=len(doc_or_text))
    doc = ExtractedDocument(
        filename=source_file,
        subject=subject,
        year=year,
        pages=[page],
        total_pages=1,
        total_chars=len(doc_or_text),
    )
    return parse_questions_from_document(doc)

